#[test]
fn resampling_and_cluster_helpers() {
    assert!(truth(
        "rand('state', 1); b = bootstrp(200, @mean, (1:10)'); rand('state', 1); b2 = bootstrp(200, @mean, (1:10)'); ok = isequal(size(b), [200 1]) && all(b >= 1 & b <= 10) && abs(mean(b) - 5.5) < 0.35 && isequal(b, b2);",
        "ok"
    ));
    assert!(truth(
        "rand('state', 1); [b, s] = bootstrp(5, @(x, y) [mean(x) mean(y)], [1 2 3]', [4 5 6]'); ok = isequal(size(b), [5 2]) && isequal(size(s), [3 5]) && all(abs(b(:, 2) - b(:, 1) - 3) < 1e-12);",
        "ok"
    ));
    assert_eq!(
        fails("bootstrp(3, @mean, [1 2 3]', [1 2]')").0,
        "stats:bootstrp:InputSizeMismatch"
    );
    assert!(truth(
        "rand('state', 4); [y, idx] = datasample((10:10:50)', 3, 'Replace', false); ok = numel(unique(idx)) == 3 && isequal(y, 10 * idx) && isequal(size(datasample([1 2; 3 4; 5 6], 4)), [4 2]);",
        "ok"
    ));
    assert_eq!(
        fails("datasample(1:3, 5, 'Replace', false)").0,
        "stats:datasample:SampleTooBig"
    );
    check(
        "clusterdata([0 0; 0 1; 10 10; 10 11], 'maxclust', 2)'",
        &[1.0, 1.0, 2.0, 2.0],
        0.0,
    );
    // silhouette: a = 1, b = 10.5 for the first point
    check(
        "silhouette([0; 1; 10; 11], [1; 1; 2; 2], 'euclidean')'",
        &[
            1.0 - 1.0 / 10.5,
            1.0 - 1.0 / 9.5,
            1.0 - 1.0 / 9.5,
            1.0 - 1.0 / 10.5,
        ],
        1e-14,
    );
    check("silhouette([0; 5], [1; 2])'", &[1.0, 1.0], 0.0);
    assert!(truth(
        "Y = pdist([0; 1; 10; 11]); Z = linkage(Y, 'average'); [c, d] = cophenet(Z, Y); r = corrcoef(Y, d); ok = abs(c - r(1, 2)) < 1e-14 && isequal(d, [1 10 10 10 10 1]);",
        "ok"
    ));
}

#[test]
fn goodness_of_fit_and_fit_estimators() {
    // observed [10 20 30] against expected [20 20 20]: chi2 = 10 on 2 df, p = exp(-5)
    let it = run(
        "x = [ones(1, 10) 2 * ones(1, 20) 3 * ones(1, 30)]; [h, p, s] = chi2gof(x, 'Edges', [1.5 2.5], 'Expected', [20 20 20], 'NParams', 0); ok = s.chi2stat == 10 && s.df == 2 && isequal(s.O, [10 20 30]);",
    );
    assert_eq!(nums(&it, "h"), vec![1.0]);
    assert!((nums(&it, "p")[0] - (-5.0f64).exp()).abs() < 1e-14);
    assert_eq!(nums(&it, "ok"), vec![1.0]);
    // CDF given as a name + parameters
    assert!(truth(
        "x = [1.2 2.4 3.1 3.9 5.2 6.1 6.8 8.5 9.3 9.9 1.5 2.9 4.1 5.5 7.2 8.8 2.2 4.7 6.4 9.1 3.3 5.9 7.7 8.1 4.4]; [h, p, s] = chi2gof(x, 'Edges', [3 6 8], 'CDF', {'Uniform', 1, 10}, 'NParams', 0); ok = s.df == 3 && abs(sum(s.E) - 25) < 1e-12 && sum(s.O) == 25;",
        "ok"
    ));
    assert_eq!(
        fails("chi2gof([1 2 3 4 5 6], 'NBins', 6)").0,
        "stats:chi2gof:LowExpected"
    );
    assert_eq!(
        fails("kstest([1 2 3], 'tail', 'both')").0,
        "stats:kstest:BadTail"
    );
    assert_eq!(
        fails("kstest([1 2 3], 'alpha', 0)").0,
        "stats:kstest:BadAlpha"
    );
    assert_eq!(fails("binofit(5, 3)").0, "stats:binofit:InvalidData");
    assert_eq!(fails("expfit([-1 2])").0, "stats:expfit:BadData");
    assert_eq!(fails("poissfit([1.5 2])").0, "stats:poissfit:BadData");
    assert_eq!(fails("lognfit([0 1 2])").0, "stats:lognfit:BadData");
    // kstest with a distribution object and with an explicit CDF table
    assert!(truth(
        "x = [0.2 -1.1 0.5 1.7 -0.3 0.9 -2.2 0.1 0.4 -0.7]'; [h1, p1] = kstest(x); [h2, p2] = kstest(x, makedist('Normal')); xs = sort(x); [h3, p3] = kstest(x, 'CDF', [xs normcdf(xs)]); ok = abs(p1 - p2) < 1e-15 && abs(p1 - p3) < 1e-15;",
        "ok"
    ));
    // MLE estimators satisfy their score equations (Weibull shape, gamma shape)
    assert!(truth(
        "x = [0.8 1.3 2.1 2.9 3.7 5.2 6.1 9.8]; w = wblfit(x); g = gamfit(x); ok = abs(sum(x .^ w(2) .* log(x)) / sum(x .^ w(2)) - 1 / w(2) - mean(log(x))) < 1e-12 && abs(log(g(1) * g(2)) - log(mean(x))) < 1e-12 && abs(g(1) * g(2) - mean(x)) < 1e-12;",
        "ok"
    ));
    assert_eq!(
        fails("[a, ci] = wblfit([1 2 3]);").0,
        "stats:fit:Unsupported"
    );
    // ksdensity with an explicit bandwidth is a plain kernel average
    check(
        "ksdensity([0], 0, 'Bandwidth', 2)",
        &[1.0 / (2.0 * (2.0 * std::f64::consts::PI).sqrt())],
        1e-14,
    );
    check(
        "ksdensity([0 2], 1, 'Bandwidth', 1, 'Function', 'cdf')",
        &[(0.841_344_746_068_542_9 + 0.158_655_253_931_457_05) / 2.0],
        1e-12,
    );
    assert_eq!(
        fails("ksdensity([1 2 3], 'Support', 'positive')").0,
        "stats:ksdensity:Unsupported"
    );
}
