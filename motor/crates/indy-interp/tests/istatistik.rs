use indy_interp::Interp;

const PRELUDE: &str = r#"1;
function r=tt1(varargin), [h,p,ci,s]=ttest(varargin{:}); r=[h p ci(:)' s.tstat s.df s.sd]; end
function r=tt2(varargin), [h,p,ci,s]=ttest2(varargin{:}); r=[h p ci(:)' s.tstat s.df s.sd(:)']; end
function r=zt(varargin), [h,p,ci,z]=ztest(varargin{:}); r=[h p ci(:)' z]; end
function r=vt(varargin), [h,p,ci,s]=vartest(varargin{:}); r=[h p ci(:)' s.chisqstat s.df]; end
function r=vt2(varargin), [h,p,ci,s]=vartest2(varargin{:}); r=[h p ci(:)' s.fstat s.df1 s.df2]; end
function r=nf(varargin), [m,s,mc,sc]=normfit(varargin{:}); r=[m s mc(:)' sc(:)']; end
function r=rg(y,X), [b,bint,rr,rint,s]=regress(y,X); r=[b(:)' bint(:)' rr(:)' rint(:)' s]; end
function r=pc(X), [c,s,l,t2,e,mu]=pca(X); r=[abs(c(:))' abs(s(:))' l(:)' t2(:)' e(:)' mu(:)']; end
function r=ks1(varargin), [h,p,k]=kstest(varargin{:}); r=[h p k]; end
function r=ks2(varargin), [h,p,k]=kstest2(varargin{:}); r=[h p k]; end
function r=kd(varargin), [f,xi,bw]=ksdensity(varargin{:}); r=[f(:)' xi(:)' bw]; end
function r=ef(x), [m,ci]=expfit(x); r=[m ci(:)']; end
function r=pf(x), [m,ci]=poissfit(x); r=[m ci(:)']; end
function r=bf(x,n), [m,ci]=binofit(x,n); r=[m ci(:)']; end
function r=ns(varargin), [m,v]=normstat(varargin{:}); r=[m v]; end
function r=ws(varargin), [m,v]=wblstat(varargin{:}); r=[m v]; end
function r=gs(varargin), [m,v]=gamstat(varargin{:}); r=[m v]; end
function r=bs(varargin), [m,v]=binostat(varargin{:}); r=[m v]; end
function r=nbs(varargin), [m,v]=nbinstat(varargin{:}); r=[m v]; end
function r=ts(varargin), [m,v]=tstat(varargin{:}); r=[m v]; end
function r=knn(varargin), [i,d]=knnsearch(varargin{:}); r=[i(:)' d(:)']; end
function r=ev1(varargin), [m,v]=evstat(varargin{:}); r=[m v]; end
function r=ras(varargin), [m,v]=raylstat(varargin{:}); r=[m v]; end
function r=ec(y), [f,x]=ecdf(y); r=[f(:)' x(:)']; end
"#;

fn run(src: &str) -> Interp {
    let mut it = Interp::new();
    let full = format!("{PRELUDE}{src}");
    if let Err(e) = it.run_text(&full) {
        panic!("{}\n  -> {} ({})", src, e.message, e.identifier);
    }
    it
}

fn nums(it: &Interp, name: &str) -> Vec<f64> {
    it.get_var(name)
        .unwrap_or_else(|| panic!("no variable {}", name))
        .to_f64_vec()
        .unwrap()
}

fn check(expr: &str, want: &[f64], tol: f64) {
    let it = run(&format!("r = {expr};"));
    let got = nums(&it, "r");
    let ok = got.len() == want.len()
        && got.iter().zip(want).all(|(x, y)| {
            (x == y) || (x.is_nan() && y.is_nan()) || (x - y).abs() <= tol * (1.0 + y.abs())
        });
    assert!(ok, "{expr}:\n got  {got:?}\n want {want:?}");
}

fn fails(src: &str) -> (String, String) {
    let mut it = Interp::new();
    match it.run_text(src) {
        Ok(_) => panic!("expected an error: {}", src),
        Err(e) => (e.identifier.clone(), e.message.clone()),
    }
}

