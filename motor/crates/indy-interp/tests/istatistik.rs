fn truth(src: &str, var: &str) -> bool {
    let it = run(src);
    it.get_var(var)
        .and_then(|v| v.is_true().ok())
        .unwrap_or(false)
}

#[test]
fn special_function_edges() {
    check("gammainc([0 Inf], 2)", &[0.0, 1.0], 1e-15);
    check("gammainc(3, 0)", &[1.0], 1e-15);
    check("betainc([0 1], 2, 3)", &[0.0, 1.0], 1e-15);
    check(
        "erfinv([-1 0 1])",
        &[f64::NEG_INFINITY, 0.0, f64::INFINITY],
        0.0,
    );
    check(
        "erfcinv([0 1 2])",
        &[f64::INFINITY, 0.0, f64::NEG_INFINITY],
        0.0,
    );
    // erfc keeps relative accuracy in the tail (1 - erf would give 0)
    check("erfc(6)", &[2.151_973_671_249_891_4e-17], 1e-13);
    check("erfc(26)", &[5.663_192_408_856_143e-296], 1e-12);
    check("gammaln([1 2])", &[0.0, 0.0], 0.0);
    assert_eq!(
        fails("gammainc(1, 2, 'middle')").0,
        "MATLAB:gammainc:InvalidTailArg"
    );
    assert_eq!(fails("betainc(1.5, 2, 3)").0, "MATLAB:betainc:XOutOfRange");
    // analytic: ln Gamma at half integers, Gamma(1/2) = sqrt(pi)
    check("gammaln(0.5)", &[0.5 * std::f64::consts::PI.ln()], 1e-15);
    // large-argument regularised incomplete gamma against the chi-square identity
    check(
        "gammainc(5, 2.5) + gammainc(5, 2.5, 'upper')",
        &[1.0],
        1e-15,
    );
}

#[test]
fn distribution_edges() {
    check("normpdf(1, 0, -1)", &[f64::NAN], 0.0);
    check(
        "norminv([-0.1 0 1 1.1])",
        &[f64::NAN, f64::NEG_INFINITY, f64::INFINITY, f64::NAN],
        0.0,
    );
    check("binoinv(0.5, 10, 0.5)", &[5.0], 0.0);
    check("binopdf(2.5, 4, 0.5)", &[0.0], 0.0);
    check("poissinv(0.5, 0)", &[0.0], 0.0);
    check("tcdf(Inf, 3)", &[1.0], 0.0);
    check("expcdf(-1, 2)", &[0.0], 0.0);
    check("unifcdf([0 0.5 2], 1, 2)", &[0.0, 0.0, 1.0], 0.0);
    // inverse round trips, including the far tails
    check("normcdf(norminv(1e-12))", &[1e-12], 1e-12);
    check("tcdf(tinv(1e-8, 4), 4)", &[1e-8], 1e-10);
    check("gamcdf(gaminv(0.999999, 3, 2), 3, 2)", &[0.999999], 1e-12);
    check("betacdf(betainv(0.3, 0.5, 4), 0.5, 4)", &[0.3], 1e-12);
    check(
        "binocdf(binoinv(0.37, 30, 0.2), 30, 0.2) >= 0.37",
        &[1.0],
        0.0,
    );
    // cdf 'upper' and name-based generic calls
    check(
        "normcdf(2, 0, 1, 'upper')",
        &[0.022_750_131_948_179_207],
        1e-12,
    );
    // 1 - gamcdf(2, 3, 2) = exp(-1)(1 + 1 + 1/2)
    check(
        "cdf('Gamma', 2, 3, 2, 'upper')",
        &[2.5 * (-1.0f64).exp()],
        1e-13,
    );
    check("pdf('Binomial', 2, 4, 0.5)", &[0.375], 1e-14);
    check("icdf('t', 0.975, 10)", &[2.228_138_851_986_274], 1e-9);
    check("pdf('chi2', 3, 2)", &[0.5 * (-1.5f64).exp()], 1e-14);
    assert_eq!(fails("tcdf(1)").0, "MATLAB:minrhs");
    assert_eq!(
        fails("pdf('Nonsense', 1, 2)").0,
        "stats:pdf:UnrecognizedName"
    );
    assert_eq!(
        fails("normpdf([1 2 3], [1 2])").0,
        "MATLAB:sizeDimensionsMustMatch"
    );
    assert_eq!(
        fails("normcdf(1, 0, 1, 'sideways')").0,
        "stats:cdf:InvalidTail"
    );
}

#[test]
fn norminv_confidence_bounds_match_matlab_table() {
    // MATLAB R2025b measured values (uyumluluk wave26-norminv-*)
    check(
        "norminv([0 .1 .5 .9 1], 0, 1, 'upper')",
        &[
            f64::NEG_INFINITY,
            -1.281_551_565_544_600_5,
            0.0,
            1.281_551_565_544_600_5,
            f64::INFINITY,
        ],
        1e-12,
    );
    let it = run("[x, lo, hi] = norminv([.1 .5 .9], 2, 3, eye(2));");
    for (name, want) in [
        (
            "x",
            [-1.844_654_696_633_801_5, 2.0, 5.844_654_696_633_801_5],
        ),
        (
            "lo",
            [
                -5.030_651_009_351_967,
                0.040_036_015_459_945_506,
                2.658_658_383_915_635_7,
            ],
        ),
        (
            "hi",
            [
                1.341_341_616_084_364_3,
                3.959_963_984_540_054_5,
                9.030_651_009_351_967,
            ],
        ),
    ] {
        let got = nums(&it, name);
        for (g, w) in got.iter().zip(want) {
            assert!((g - w).abs() < 1e-12, "{name}: {got:?}");
        }
    }
    assert_eq!(
        fails("[x, lo, hi] = norminv([.1 .5 .9], 2, 3, [1 2; 2 1]);").0,
        "stats:norminv:BadCovarianceSymPos"
    );
    assert!(truth(
        "[x, lo, hi] = norminv([.1 .5 .9], 2, 3, zeros(2)); ok = isequal(x, lo) && isequal(x, hi);",
        "ok"
    ));
    // normcdf bounds bracket the estimate
    assert!(truth(
        "[p, lo, hi] = normcdf(0.5, 0, 1, [0.01 0; 0 0.02]); ok = lo < p && p < hi;",
        "ok"
    ));
}

